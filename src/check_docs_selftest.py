"""ทดสอบตัวตรวจใน `check_docs.py` ด้วยการแกล้งละเมิดกฎทุกข้อ

ครอบคลุม `check_tables()` ซึ่งตรวจเลขตาราง และ `check_section_refs()`
ซึ่งตรวจว่าการอ้างถึงหัวข้อชี้ไปที่หัวข้อที่มีอยู่จริง

## ทำไมต้องมีไฟล์นี้

กฎของโปรเจกต์คือ **ตัวตรวจทุกตัวต้องทดสอบสองทาง** ทางแรกคือรันกับของจริง
แล้วต้องเงียบ ซึ่งเกิดขึ้นเองทุกครั้งที่รัน `check_docs.py`
ทางที่สองคือแกล้งทำให้ผิดแล้วต้องจับได้ ซึ่ง**ไม่เกิดขึ้นเองเลย**
ถ้าไม่มีใครเขียนไว้ จึงเป็นไฟล์นี้

> **ตัวตรวจที่ไม่เคยจับอะไรได้ อันตรายกว่าตัวตรวจที่เตือนผิด**
> เพราะมันให้ความมั่นใจปลอมๆ

## ข้อควรระวังของตัวการทดสอบเอง

1. **ต้องยืนยันว่าแก้ไฟล์สำเร็จจริง** เคยใช้ `sed` แล้วไม่ match
   เพราะเรื่อง escape ของ regex **สคริปต์ทดสอบจึงไม่ได้แก้อะไรเลย
   แล้วผลออกมาเป็น "ผ่าน"** จึงมี `assert` คุมทั้งก่อนและหลังการแก้

2. **ต้องคืนไฟล์ให้ได้แม้ถูกขัดจังหวะ** ไฟล์นี้แก้เอกสารจริงชั่วคราว
   ถ้าตายกลางทางโดยไม่คืน เอกสารจะค้างอยู่ในสภาพที่ถูกทำให้พัง
   จึงอยู่ใน `try/finally`

รัน:
    python src/check_docs_selftest.py
"""
from __future__ import annotations

import subprocess
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from src.paths import repo_root  # noqa: E402

ROOT = repo_root()
DOC = ROOT / "docs/coop-proposal.md"
PY = ROOT / "venv/Scripts/python.exe"
if not PY.exists():                      # บน Pi ใช้ venv แบบ POSIX
    PY = Path(sys.executable)

# (ชื่อการทดสอบ, ข้อความเดิม, ข้อความใหม่, ข้อความที่ต้องพบในผล)
CASES = [
    ("ลบคำบรรยายของตารางหนึ่ง",
     "**ตารางที่ 6.2** อัตราการย่อขนาดข้อมูลเมื่อเทียบกับตัวตั้งสามแบบ\n\n",
     "",
     "ไม่มีคำบรรยายกำกับ"),
    ("ลบการอ้างถึงในความเรียง",
     "ตัวตั้งสามแบบและผลที่ได้แสดงดังตารางที่ 6.2",
     "ตัวตั้งสามแบบและผลที่ได้แสดงไว้ข้างล่าง",
     "ไม่มีความเรียงใดอ้างถึง"),
    # ต้องนำด้วยขึ้นบรรทัดใหม่ เพื่อให้ตรงกับคำบรรยายในเนื้อหา
    # ไม่ใช่บรรทัดในสารบัญ ซึ่งขึ้นต้นด้วย "- " และอยู่ก่อนในไฟล์
    # (รอบแรกลืมข้อนี้ การทดสอบจึงไปแก้สารบัญ แล้วรายงานว่าไม่ผ่าน)
    ("ทำให้เลขขาดช่วง",
     "\n**ตารางที่ 6.3** ลำดับการทำงาน",
     "\n**ตารางที่ 6.4** ลำดับการทำงาน",
     "ไม่เรียงต่อเนื่อง"),
    ("ทำให้สารบัญไม่ตรงกับคำบรรยาย",
     "- **ตารางที่ 9.2** ความเสี่ยงของโครงงานและแผนรองรับ",
     "- **ตารางที่ 9.2** ความเสี่ยงของโครงงาน",
     "สารบัญตารางไม่ตรงกับคำบรรยาย"),
    # บั๊กที่เกิดขึ้นจริงตอนใส่เลขตารางรอบแรก คำบรรยายไปติดกับย่อหน้า
    ("ลบบรรทัดว่างระหว่างย่อหน้ากับคำบรรยาย",
     "แสดงดังตารางที่ 9.1\n\n**ตารางที่ 9.1**",
     "แสดงดังตารางที่ 9.1\n**ตารางที่ 9.1**",
     "จัดบรรทัดว่างไม่ถูก"),
    # ข้อนี้ตรวจว่าตัวตรวจจะส่งเสียงเมื่อ**ตัวมันเองใช้งานไม่ได้**
    ("เปลี่ยนรูปแบบคำบรรยายทั้งฉบับ",
     "**ตารางที่ ", "**Table ",
     "ทำให้ตัวตรวจตายเงียบ"),
    # การอ้างถึงหัวข้อที่ถูกยุบไปแล้ว ซึ่งเกิดขึ้นจริงตอนยุบหัวข้อ 3 และ 4
    ("อ้างถึงหัวข้อที่ไม่มีอยู่",
     "ตามหัวข้อ 3 ข้อ 2", "ตามหัวข้อ 3.2",
     'อ้างถึง "หัวข้อ 3.2" แต่ไม่มีหัวข้อนั้นในไฟล์'),
    # และตัวตรวจนั้นต้องส่งเสียงเมื่อหารูปแบบหัวข้อไม่พบเลย
    # ต้องแทนที่เครื่องหมายหัวข้อทุกระดับ ไม่ใช่เฉพาะระดับ 1 เพราะหัวข้อ
    # ระดับ 3 อย่าง "### 5.2.1" ก็มีเลขและยังนับเป็นหัวข้อ
    ("เปลี่ยนรูปแบบหัวข้อทั้งฉบับ",
     "\n#", "\n@@",
     "ไม่พบหัวข้อที่มีเลขเลย"),
]


def run_checker() -> str:
    r = subprocess.run([str(PY), "src/check_docs.py"], cwd=ROOT,
                       capture_output=True, text=True, encoding="utf-8")
    return r.stdout or ""


def main() -> int:
    orig = DOC.read_text(encoding="utf-8")
    fails = []
    try:
        for label, old, new, expect in CASES:
            assert old in orig, (
                f"[{label}] ไม่พบข้อความที่จะแก้ -> การทดสอบนี้ตายเงียบ")
            n = -1 if label.startswith("เปลี่ยนรูปแบบ") else 1
            DOC.write_text(orig.replace(old, new, n), encoding="utf-8")
            assert DOC.read_text(encoding="utf-8") != orig, (
                f"[{label}] แก้ไฟล์ไม่สำเร็จ แต่เกือบรายงานว่าผ่าน")

            ok = expect in run_checker()
            print(f"{'ผ่าน   ' if ok else 'ไม่ผ่าน'} {label}")
            if not ok:
                fails.append(label)
                print("        ไม่พบข้อความที่คาดไว้:", expect)
    finally:
        DOC.write_text(orig, encoding="utf-8")

    assert DOC.read_text(encoding="utf-8") == orig, "คืนไฟล์ไม่สำเร็จ"
    print()
    if fails:
        print(f"❌ ไม่ผ่าน {len(fails)} ข้อ: {fails}")
        return 1
    print(f"✅ ผ่านทั้ง {len(CASES)} ข้อ และคืนเอกสารกลับเรียบร้อย")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
